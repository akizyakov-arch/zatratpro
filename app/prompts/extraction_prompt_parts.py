EXTRACTION_PROMPT_BASE = '''
Извлеки структурированные данные из OCR-текста документа.
Верни только один JSON-объект без markdown и без пояснений.

Контракт ответа:
{
  "document_type": "unknown",
  "external_document_number": null,
  "incoming_number": null,
  "vendor": null,
  "vendor_inn": null,
  "vendor_kpp": null,
  "date": null,
  "currency": "RUB",
  "total": null,
  "vat_total_amount": null,
  "vat_scope": "unknown",
  "is_fiscalized": null,
  "items": [
    {
      "name": null,
      "quantity": null,
      "price": null,
      "line_total": null,
      "vat_label": null,
      "vat_amount": null
    }
  ]
}

Допустимые document_type:
goods_invoice, service_act, upd, vat_invoice, cash_receipt, bso, transport_invoice, cash_out_order, unknown

Допустимые vat_scope:
document, mixed, no_vat, unknown

Общие правила:
- если значение не видно надежно, верни null
- не придумывай значения
- не восстанавливай значения по догадке
- используй только данные, явно присутствующие в OCR-тексте
- если данные сомнительны, выбирай более консервативный вариант
- лучше вернуть меньше данных, чем добавить ложные
- очищай OCR-мусор в vendor и номерах документа
- date возвращай в формате YYYY-MM-DD
- ИНН и КПП возвращай только цифрами
- числовые поля возвращай как числа без валюты и пробелов
- если тип документа неочевиден, верни unknown
- items должен быть массивом; если надежных позиций нет, верни []

Правила по позициям:
- извлекай только реальные строки таблицы или списка позиций
- не создавай позиции из итогов, НДС-строк, подписей, печатей, реквизитов, адресов, примечаний и свободного текста
- не создавай позицию, если строка выглядит как OCR-мусор, продолжение другой строки или дубль
- если название не читается, но сама строка таблицы очевидна и числовые колонки читаются, можно оставить name = null
- не добавляй фиктивные названия вроде "Без названия", "Товар", "Позиция"
- если позиция не содержит надежных числовых данных и надежного названия, не включай ее в items
- если line_total явно указан, используй его
- если quantity и price надежны, а line_total не указан, можно вычислить line_total = quantity * price
- vat_label и vat_amount на позиции заполняй только если НДС явно относится к этой позиции

Правила по total:
- total заполняй только если итоговая сумма документа явно указана
- не вычисляй total из позиций, если итоговая сумма в документе не видна явно
- total может быть указан рядом с пометкой Итого/Сумма/Всего/К оплате
- не добавляй итоговую сумму как отдельную позицию items
- если итоговая сумма видна явно, она имеет приоритет над суммой по распознанным позициям

VAT и фискализация:
- заполняй vat_* только если НДС явно указан
- если НДС не виден, используй vat_total_amount = null и vat_scope = unknown
- если явно указано "без НДС" для всего документа, используй vat_scope = no_vat
- если НДС относится только к части позиций, а другая часть отмечена как "без НДС", используй vat_scope = mixed
- для чеков и БСО, если в итоговом блоке одновременно видны положительная сумма НДС и любая сумма/пометка "без НДС", используй vat_scope = mixed
- используй vat_scope = document только если НДС относится ко всему документу
- заполняй is_fiscalized только для чеков и БСО с явными фискальными реквизитами
- для накладных, актов, УПД, счетов-фактур и транспортных накладных is_fiscalized обычно null
'''.strip()


